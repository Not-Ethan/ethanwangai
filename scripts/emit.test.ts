import { describe, it, expect } from 'vitest';
import { buildBench } from '@/bench/counts';
import { MACHINE_NAMES } from '@/bench/types';
import { emitAll } from './emitCore';

const HEADER = '// generated by scripts/emit.ts — do not edit\n';
const count = (s: string, needle: string) => s.split(needle).length - 1;

describe('emitAll', () => {
  const { files } = emitAll();

  it('emits the hero plates as NDC svg string constants with their aspects', () => {
    const hero = files['src/generated/heroPlate.ts'];
    expect(hero.startsWith(HEADER)).toBe(true);
    expect(hero).toContain('viewBox="-1 -1 2 2"');
    expect(hero).toContain('export const HERO_PLATE_LANDSCAPE = \'<svg');
    expect(hero).toContain('export const HERO_PLATE_PORTRAIT = \'<svg');
    expect(hero).toContain('export const HERO_ASPECT_LANDSCAPE = 1.6;');
    expect(hero).toContain('export const HERO_ASPECT_PORTRAIT = 0.462;');
  });

  it('prints the desktop total from the layout', () => {
    const counts = files['src/generated/counts.ts'];
    expect(counts.startsWith(HEADER)).toBe(true);
    const total = counts.match(/desktop: \{ total: (\d+),/);
    expect(total).not.toBeNull();
    expect(Number(total![1])).toBe(buildBench('desktop').counts.total);
  });

  it('keeps the poster to at most 800 rects inside 1200 × 630, in all three tones', () => {
    const poster = files['src/generated/posterPlate.ts'];
    expect(poster.startsWith(HEADER)).toBe(true);
    const rects = [...poster.matchAll(/\[(\d+), (\d+), (\d+), (\d+), (\d+)\]/g)].map((m) => m.slice(1).map(Number));
    expect(rects.length).toBeGreaterThan(100);
    expect(rects.length).toBeLessThanOrEqual(800);
    for (const [x, y, w, h, tone] of rects) {
      expect(w).toBeGreaterThan(0);
      expect(h).toBeGreaterThan(0);
      expect(x + w).toBeLessThanOrEqual(1200);
      expect(y + h).toBeLessThanOrEqual(630);
      expect([0, 1, 2]).toContain(tone);
    }
    expect(new Set(rects.map((r) => r[4]))).toEqual(new Set([0, 1, 2]));
  });

  it('writes one ink plate per built machine, each capped at 2,500 rects', () => {
    const names = MACHINE_NAMES.filter((n) => n !== 'visitor');
    expect(Object.keys(files).filter((k) => k.startsWith('public/plates/')).sort()).toEqual(names.map((n) => `public/plates/${n}.svg`).sort());
    for (const n of names) {
      const plate = files[`public/plates/${n}.svg`];
      expect(plate).toContain('viewBox="-1 -1 2 2"');
      expect(count(plate, '<rect')).toBeGreaterThan(0);
      expect(count(plate, '<rect')).toBeLessThanOrEqual(2500);
    }
  });

  it('is idempotent: a second run yields the same strings', () => {
    expect(emitAll().files).toEqual(files);
  });
});
